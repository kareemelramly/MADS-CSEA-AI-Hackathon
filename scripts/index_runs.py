"""Generate docs/demo_runs.md from decision_log.json (SRS LOG-6). Generated, never edited."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    log = json.load(open(os.path.join(ROOT, "decision_log.json"), encoding="utf-8"))
    runs = {}
    for e in log:
        rid = e.get("run_id")
        if not rid:
            continue
        r = runs.setdefault(rid, {"brief": None, "gates": [], "files": [], "tiers": set(), "outcome": None})
        if e["action"] == "start_run":
            r["brief"] = e.get("brief_idea")
        if e["agent"] == "gate":
            r["gates"].append(f"{e['action']}: `{e.get('outcome')}`")
        if e["action"] == "write_output":
            r["files"].append(e["path"])
        if e.get("model"):
            r["tiers"].add(e["model"])
        if e["action"] == "end_run":
            r["outcome"] = e.get("outcome")
    L = ["# Demo runs (generated by scripts/index_runs.py from decision_log.json)", "",
         "Each run ID links to the files it wrote. A file marked by a higher `_a<k>` number supersedes the earlier attempt.", ""]
    for rid, r in runs.items():
        L += [f"## Run `{rid}`", "", f"- Brief idea: {r['brief']}", f"- Final outcome: `{r['outcome']}`",
              f"- Gates: {'; '.join(r['gates']) or 'none'}", f"- Model tiers used: {', '.join(sorted(r['tiers'])) or 'none (no model call)'}", "", "Files:", ""]
        L += [f"- [{f}](../{f})" for f in r["files"]] + [""]
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    open(os.path.join(ROOT, "docs", "demo_runs.md"), "w", encoding="utf-8").write("\n".join(L))
    print(f"docs/demo_runs.md: {len(runs)} runs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
